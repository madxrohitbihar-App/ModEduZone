export function pickLectureVideoId(seedKey: string, index: number): string {
  const lower = seedKey.toLowerCase();
  const pool =
    lower.includes('gyan') || lower.includes('polity') || lower.includes('history') || lower.includes('bihar')
      ? INSTITUTE_VIDEO_POOL.gyan
      : lower.includes('target')
        ? INSTITUTE_VIDEO_POOL['target-board']
        : lower.includes('parmar') || lower.includes('quant') || lower.includes('reason')
          ? INSTITUTE_VIDEO_POOL.parmar
          : lower.includes('disha') || lower.includes('phy') || lower.includes('chem') || lower.includes('math')
            ? INSTITUTE_VIDEO_POOL.disha
            : INSTITUTE_VIDEO_POOL.default;
  return pool[index % pool.length];
}

